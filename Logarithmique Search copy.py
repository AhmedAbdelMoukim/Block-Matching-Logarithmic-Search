def logarithmic_search(block1, image2, block_size, i, j, search_radius=20):
    height = image2.shape[0]
    width = image2.shape[1]

    best_match_position = np.array([i, j])
    best_metric_value = float('inf')

     
    while search_radius > 1:
        
        for dy in range(-search_radius, search_radius + 1, search_radius ):
            for dx in range(-search_radius, search_radius + 1, search_radius ):
                new_position = best_match_position + np.array([dx, dy])
                new_position = np.clip(new_position, [0, 0], [height - block_size, width - block_size])

                if new_position[0] >= 0 and new_position[1] >= 0:
                    block2 = image2[new_position[0]:new_position[0] + block_size, new_position[1]:new_position[1] + block_size, :]
                    if block2.shape[0] > 0 and block2.shape[1] > 0:
                        current_metric_value = calculate_metric(block1, block2)
                        if current_metric_value < best_metric_value:
                            best_metric_value = current_metric_value
                            best_match_position = new_position

        search_radius = search_radius //2

    return best_match_position


def calculate_metric(block1, block2):
    return np.mean((block1 - block2) ** 2)

